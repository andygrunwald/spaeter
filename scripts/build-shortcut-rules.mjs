// Generates the Cherri includes for the iPhone Shortcut from extension/lib/rules.js,
// so the Shortcut and the Chrome extension classify links and name tasks the same way.
// Run via `make shortcuts` (or `npm run shortcut-rules`); the output is git-ignored.
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { DOMAINS, PRESETS, TYPES } from '../extension/lib/rules.js';

const HEADER = '// Generated by scripts/build-shortcut-rules.mjs from extension/lib/rules.js. Do not edit.';
const PRESET_LABELS = { de: 'Deutsch', en: 'English' };

export function hostRegex(domains) {
  return `(?i)(^|\\.)(${domains.map((domain) => domain.replaceAll('.', '\\.')).join('|')})$`;
}

// Cherri raw text ('…') can't contain a single quote.
function rawText(value) {
  if (value.includes("'")) throw new Error(`Value must not contain a single quote: ${value}`);
  return `'${value}'`;
}

// Expects the constant `host`; sets @type to "read", "watch" or "listen".
export function renderClassify() {
  const lines = [HEADER, '@type = "read"'];
  for (const [type, domains] of Object.entries(DOMAINS)) {
    lines.push(
      `const ${type}Match = matchText(${rawText(hostRegex(domains))}, host)`,
      `if ${type}Match {`,
      `    @type = "${type}"`,
      '}',
    );
  }
  return `${lines.join('\n')}\n`;
}

// Asks for the language and sets @readTemplate, @readTag, @watchTemplate, … accordingly.
export function renderPresets() {
  const lines = [HEADER, 'menu "Language of task names" {'];
  for (const [preset, values] of Object.entries(PRESETS)) {
    if (!PRESET_LABELS[preset]) throw new Error(`Missing label for preset "${preset}"`);
    lines.push(`    item "${PRESET_LABELS[preset]}":`);
    for (const type of TYPES) {
      lines.push(
        `        @${type}Template = ${rawText(values[type].template)}`,
        `        @${type}Tag = ${rawText(values[type].tag)}`,
      );
    }
  }
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await mkdir('ios/generated', { recursive: true });
  await writeFile('ios/generated/classify.cherri', renderClassify());
  await writeFile('ios/generated/presets.cherri', renderPresets());
  console.log('Generated ios/generated/classify.cherri and ios/generated/presets.cherri');
}
